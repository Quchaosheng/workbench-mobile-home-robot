#!/usr/bin/env python3
"""Regenerate generated/revision-d-frames.json from the expanded model (#327).

The artifact is the machine-readable answer to "what does this model claim, and
which design-spec.json number does each claim come from". It is generated, and
``--check`` regenerates and compares, so a hand-edited or stale artifact fails
rather than being read as current.

Determinism is a hard requirement: no timestamp, host name, absolute path or
iteration-order-dependent key may enter the output, so two runs against one
commit produce identical bytes. ``--check`` exercises exactly that.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import description_model as model

HEADER = (
    "Generated by robot/description/revision_d/tools/generate_frames.py. "
    "Do not edit by hand; run `make description-check`, which regenerates and diffs."
)


def build() -> dict:
    spec = model.load_spec()
    root = model.expand()
    poses = model.forward_kinematics(root)
    limits = model.joint_limits(root)

    arm_joints = []
    for name in model.arm_joint_names():
        entry = limits[name]
        arm_joints.append(
            {
                "name": name,
                "type": entry["type"],
                "lower_rad": round(entry["lower"], 9),
                "upper_rad": round(entry["upper"], 9),
                "effort_nm": entry["effort"],
                "velocity_rad_s": entry["velocity"],
            }
        )

    wheels = []
    for name in model.STEER_DRIVE_MODULES:
        centre = model.wheel_centres(poses)[name]
        wheels.append(
            {
                "module": name,
                "steering_joint": f"{name}_steering_joint",
                "drive_joint": f"{name}_drive_joint",
                "wheel_link": f"{name}_wheel",
                "wheel_centre_m": [round(value, 6) for value in centre],
                "wheel_radius_m": spec["chassis"]["wheel_diameter_mm"] / 2000.0,
            }
        )

    stabilizers = []
    for name in model.STABILIZERS:
        pad = poses[f"{name}_pad"]
        stabilizers.append(
            {
                "name": name,
                "deploy_joint": f"{name}_deploy_joint",
                "pad_link": f"{name}_pad",
                "deployed_pad_centre_m": [round(value, 6) for value in pad],
            }
        )

    return {
        "_generated": HEADER,
        "revision": spec["revision"],
        "source_spec": "hardware/mechanical/design-spec.json",
        "units": {"length": "m", "angle": "rad", "mass": "kg"},
        "design_spec_anchors": {
            "base_top_z_m": spec["coordinate_system"]["base_top_z_mm"] / 1000.0,
            "stowed_head_top_z_m": spec["coordinate_system"]["head_top_stowed_z_mm"] / 1000.0,
            "lift_travel_m": spec["lifting_platform"]["travel"] / 1000.0,
            "shoulder_min_z_m": spec["lifting_platform"]["minimum_shoulder_height"] / 1000.0,
            "shoulder_max_z_m": spec["lifting_platform"]["maximum_shoulder_height"] / 1000.0,
            "chassis_width_m": spec["chassis"]["width"] / 1000.0,
            "chassis_depth_m": spec["chassis"]["depth"] / 1000.0,
            "wheelbase_m": spec["chassis"]["wheelbase"] / 1000.0,
            "track_m": spec["chassis"]["track"] / 1000.0,
            "ground_clearance_m": spec["chassis"]["ground_clearance"] / 1000.0,
            "arm_reach_m": spec["manipulator"]["reach_mm"] / 1000.0,
            "shoulder_center_spacing_m": spec["shoulder_mounts"]["center_spacing_mm"] / 1000.0,
            "stabilized_support_half_m": (
                spec["stability_analysis"]["support_polygons"]["stabilized"]["vertices_mm"][2][0] / 1000.0
            ),
        },
        "counts": {
            "links": len(model.link_names(root)),
            "joints": len(model.joint_names(root)),
            "revolute_joints": sum(1 for joint in root.findall("joint") if joint.get("type") == "revolute"),
            "prismatic_joints": sum(1 for joint in root.findall("joint") if joint.get("type") == "prismatic"),
            "fixed_joints": sum(1 for joint in root.findall("joint") if joint.get("type") == "fixed"),
            "manipulator_revolute_axes": len(arm_joints),
            "steer_drive_modules": len(wheels),
            "stabilizers": len(stabilizers),
        },
        "root_link": model.root_links(root)[0],
        "manipulator_joints": arm_joints,
        "steer_drive_modules": wheels,
        "stabilizers": stabilizers,
        "camera_optical_frames": [
            {"name": name, "optical_link": f"{name}_optical", "body_link": f"{name}_body"}
            for name in model.CAMERA_NAMES
        ],
        "key_poses_m": {
            "base_link": [round(value, 6) for value in poses["base_link"]],
            "torso": [round(value, 6) for value in poses["torso"]],
            "head_display": [round(value, 6) for value in poses["head_display"]],
            "head_top_z": round(poses["head_display"][2] + spec["head"]["height"] / 2000.0, 6),
            "lift_carriage": [round(value, 6) for value in poses["lift_carriage"]],
            "arm_left_tool0": [round(value, 6) for value in poses["arm_left_tool0"]],
            "arm_right_tool0": [round(value, 6) for value in poses["arm_right_tool0"]],
        },
        "known_divergences": [
            {
                "pointer": item.pointer,
                "spec_value": item.spec_value,
                "model_value": item.model_value,
                "reason": item.reason,
            }
            for item in model.known_divergences()
        ],
        "status": {
            "hardware": "NOT_EXECUTED",
            "hil": "NOT_EXECUTED",
            "physical_validation": spec["validation_status"],
        },
    }


def _serialize(payload: dict) -> str:
    return json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=model.GENERATED)
    parser.add_argument(
        "--check",
        action="store_true",
        help="regenerate and fail if the committed artifact differs",
    )
    args = parser.parse_args(argv)

    payload = build()
    expected = _serialize(payload)

    if args.check:
        if not args.output.is_file():
            print(f"missing generated artifact: {args.output}", file=sys.stderr)
            return 1
        actual = args.output.read_text(encoding="utf-8")
        if actual != expected:
            print(
                f"{args.output} is stale or hand-edited; run "
                "python3 robot/description/revision_d/tools/generate_frames.py",
                file=sys.stderr,
            )
            return 1
        print(f"description frames are current: {args.output}")
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(expected, encoding="utf-8")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
